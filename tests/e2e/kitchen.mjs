/** Mobile kitchen workflow; uses only a temporary, isolated browser profile. */
import { chromium } from "playwright";
import { spawn } from "node:child_process";
import { mkdirSync } from "node:fs";
import assert from "node:assert/strict";
const port = 3213, base = `http://localhost:${port}`;
const server = spawn(process.execPath,["node_modules/next/dist/bin/next","start","-p",String(port)],{stdio:["ignore","pipe","pipe"]});
let browser;
try {
  await new Promise((resolve,reject) => { const timer=setTimeout(()=>reject(new Error("Server timeout")),30000);server.stdout.on("data",d=>{if(/Ready/.test(String(d))){clearTimeout(timer);resolve();}});server.stderr.on("data",d=>process.stderr.write(d));server.once("exit",()=>reject(new Error("Server exited"))); });
  browser = await chromium.launch();
  const context = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const page = await context.newPage(); const errors=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto(base+"/nutricion?tab=cocina",{waitUntil:"networkidle"});
  await page.getByRole("heading",{name:"Mi cocina",exact:true}).waitFor();
  await page.getByRole("button",{name:"Añadir alimento"}).click();
  await page.getByLabel("Alimento del catálogo").fill("Tomate");
  await page.getByLabel("Gramos disponibles").fill("400");
  await page.getByRole("button",{name:"Guardar existencias"}).click();
  await page.getByRole("heading",{name:"Tomate",exact:true}).waitFor();
  console.log("PASS añadir tomate con cantidad conocida");
  await page.getByRole("button",{name:"Añadir alimento"}).click();
  await page.getByLabel("Alimento del catálogo").fill("Un producto sin catalogar");
  await page.getByLabel("Conozco la cantidad aproximada").uncheck();
  await page.getByRole("button",{name:"Guardar existencias"}).click();
  await page.getByText("Cantidad por confirmar").waitFor();
  console.log("PASS inventario sin cantidades inventadas");
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false,"no horizontal overflow");
  for (let i=0; i<3 && await page.locator(".toast-item").count(); i++) await page.locator(".toast-item").first().click();
  mkdirSync("tests/e2e/screenshots",{recursive:true});
  await page.screenshot({path:"tests/e2e/screenshots/kitchen-mobile.png",fullPage:true});
  await page.goto(base+"/nutricion?tab=menu",{waitUntil:"networkidle"});
  const generate = page.getByRole("button",{name:/Generar menú|Regenerar/}).first();
  await generate.waitFor();await generate.click();
  await page.getByRole("button",{name:"Cambiar",exact:true}).first().waitFor();
  await page.getByRole("button",{name:"Cambiar",exact:true}).first().click();
  await page.getByRole("button",{name:/Un ingrediente/}).click();
  await page.getByRole("heading",{name:"Cambiar ingrediente"}).waitFor();
  await page.getByLabel("Ingrediente a cambiar").selectOption({label:"Pan integral de trigo"});
  await page.getByRole("heading",{name:"Alternativas",exact:true}).waitFor();
  assert.ok(await page.locator(".ingredient-option").count());
  await page.locator(".ingredient-option").first().click();
  await page.getByText("Así queda tu plato").waitFor();
  await page.locator(".swap-preview").scrollIntoViewIfNeeded();
  await page.screenshot({path:"tests/e2e/screenshots/ingredient-swap-mobile.png"});
  await page.getByRole("button",{name:"Aplicar a esta comida"}).click();
  await page.getByRole("heading",{name:"Cambiar ingrediente"}).waitFor({state:"hidden"});
  console.log("PASS variante de ingrediente con previsualización y guardado");
  await page.goto(base+"/nutricion?tab=cocina",{waitUntil:"networkidle"});
  await page.getByRole("heading",{name:"Mi cocina",exact:true}).waitFor();
  await context.setOffline(true);
  await page.reload({waitUntil:"networkidle"});
  await page.getByRole("heading",{name:"Mi cocina",exact:true}).waitFor();
  await page.getByRole("heading",{name:"Tomate",exact:true}).waitFor();
  console.log("PASS inventario disponible sin conexión");
  assert.deepEqual(errors,[]);
} finally { await browser?.close();server.kill(); }
