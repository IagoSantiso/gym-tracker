/** Day-first navigation, disclosure, keyboard access and responsive layout. */
import { chromium } from "playwright";
import { spawn } from "node:child_process";
import { mkdirSync } from "node:fs";
import assert from "node:assert/strict";
const port=3217,base=`http://localhost:${port}`;
const server=spawn(process.execPath,["node_modules/next/dist/bin/next","start","-p",String(port)],{stdio:["ignore","pipe","pipe"]});
let browser;
try {
  await new Promise((resolve,reject)=>{const t=setTimeout(()=>reject(new Error("Server timeout")),30000);server.stdout.on("data",d=>{if(/Ready/.test(String(d))){clearTimeout(t);resolve();}});server.stderr.on("data",d=>process.stderr.write(d));server.once("exit",()=>reject(new Error("Server exited")));});
  browser=await chromium.launch();
  const ctx=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const page=await ctx.newPage();const errors=[];page.on("pageerror",e=>errors.push(e.stack));
  await page.goto(base,{waitUntil:"networkidle"});
  await page.getByRole("heading",{name:"Hoy",exact:true}).waitFor();
  await page.getByRole("heading",{name:"Tu energía de hoy",exact:true}).waitFor();
  assert.ok(await page.getByText("Gasto estimado del día",{exact:true}).isVisible());
  assert.equal(await page.getByRole("heading",{name:"Balance del día"}).count(),0,"health details are loaded only when requested");
  assert.equal(await page.locator('nav[aria-label="Secciones principales"] a').count(),4,"four destinations plus More");
  await page.getByRole("button",{name:"Más",exact:true}).click();
  await page.locator("#more-sheet").getByRole("link",{name:"Entrenamiento",exact:true}).waitFor();
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("#more-sheet").count(),0,"Escape dismisses the navigation sheet");
  assert.equal(await page.locator('[aria-controls="more-sheet"]').getAttribute("aria-expanded"),"false");
  await page.getByRole("button",{name:"Registrar",exact:true}).click();
  await page.getByRole("button",{name:"Peso",exact:true}).click();
  await page.getByLabel("Peso en kg").fill("82");
  await page.getByRole("button",{name:"Guardar",exact:true}).click();
  await page.getByText("Peso guardado",{exact:true}).waitFor();
  assert.equal(new URL(page.url()).pathname,"/","logging stays on Today");
  console.log("PASS Hoy: registro único, métricas bajo demanda y navegación accesible");
  await page.getByRole("link",{name:"Preparar mi menú",exact:true}).click();
  await page.getByRole("button",{name:"Generar menú",exact:true}).click();
  await page.locator(".menu-day .meal-card").first().waitFor();
  assert.equal(await page.locator(".day-picker [role=tab]").count(),7);
  assert.equal(await page.locator(".menu-day .meal-card").count(),4,"only the selected day is expanded");
  const selected=page.locator('.day-picker [aria-selected="true"]');
  const before=await selected.getAttribute("aria-label");
  await selected.focus();await page.keyboard.press("ArrowRight");
  assert.notEqual(await page.locator('.day-picker [aria-selected="true"]').getAttribute("aria-label"),before,"arrow key changes the selected day");
  assert.equal(await page.locator('.day-picker [aria-selected="true"]').evaluate(e=>e===document.activeElement),true);
  await page.getByText("Vista de la semana",{exact:true}).click();
  assert.equal(await page.locator(".menu-week-summary li").count(),7,"weekly overview remains available");
  await page.locator(".menu-week-summary li button").first().click();
  assert.equal(await page.locator(".menu-week-summary").getAttribute("open"),null);
  mkdirSync("tests/e2e/screenshots",{recursive:true});
  for(let i=0;i<3 && await page.locator(".toast-item").count();i++)await page.locator(".toast-item").first().click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({animations:"disabled",path:"tests/e2e/screenshots/menu-day-mobile.png",fullPage:true});
  console.log("PASS menú: un día visible, resumen semanal y navegación con teclado");
  await page.goto(base,{waitUntil:"networkidle"});
  await page.locator(".today-meal").first().waitFor();
  assert.equal(await page.locator(".today-meal").count(),4,"all meals visible as collapsed summaries");
  assert.equal(await page.locator(".today-meal[open]").count(),0);
  await page.locator(".today-meal > summary").first().click();
  await page.locator(".today-meal").first().getByRole("button",{name:"Cambiar",exact:true}).click();
  await page.getByRole("button",{name:/Un ingrediente/}).click();
  await page.getByRole("heading",{name:"Cambiar ingrediente",exact:true}).waitFor();
  await page.locator(".ingredient-option").first().click();
  await page.getByText("Así queda tu plato",{exact:true}).waitFor();
  const apply=page.getByRole("button",{name:"Aplicar a esta comida",exact:true});
  const box=await apply.boundingBox();
  assert.ok(box && box.y>=0 && box.y+box.height<=844,"apply action remains visible on mobile");
  await page.screenshot({animations:"disabled",path:"tests/e2e/screenshots/change-meal-mobile.png"});
  await page.getByRole("button",{name:"Cerrar",exact:true}).click();
  for(let i=0;i<3 && await page.locator(".toast-item").count();i++)await page.locator(".toast-item").first().click();
  await page.screenshot({animations:"disabled",path:"tests/e2e/screenshots/today-mobile.png",fullPage:true});
  await page.screenshot({animations:"disabled",path:"tests/e2e/screenshots/today-mobile-viewport.png"});
  for(const width of [320,768,1280]){
    await page.setViewportSize({width,height:900});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`no overflow at ${width}px`);
  }
  await page.screenshot({animations:"disabled",path:"tests/e2e/screenshots/today-desktop.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.emulateMedia({colorScheme:"dark"});
  await page.waitForFunction(()=>document.documentElement.dataset.theme==="dark");
  await page.screenshot({animations:"disabled",path:"tests/e2e/screenshots/today-dark.png",fullPage:true});
  await page.getByRole("button",{name:"Necesito ajustar el día",exact:true}).click();
  await page.getByLabel("Qué has comido o qué tienes").waitFor();
  assert.equal(await page.locator("dialog[open]").count(),1);
  await page.getByRole("button",{name:"Cerrar",exact:true}).click();
  await page.locator(".today-disclosure > summary").filter({hasText:"Nutrición y salud en detalle"}).click();
  await page.getByRole("heading",{name:"Balance del día",exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log("PASS cambio desde Hoy: vista previa, acción visible y detalles accesibles en móvil/escritorio");
} finally {await browser?.close();server.kill();}
