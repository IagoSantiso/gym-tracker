const TZ = "Europe/Madrid";
const pad = (n: number) => String(n).padStart(2, "0");

/** CSV sintético con formato LibreView (EN, MM-DD-YYYY). */
function libreCsv(opts: { days: number; start?: Date; unit?: "mg/dL" | "mmol/L"; value?: (i: number) => number | string; spanish?: boolean; dmy?: boolean; delimiter?: string }) {
  const unit = opts.unit ?? "mg/dL";
  const d = opts.delimiter ?? ",";
  const head = opts.spanish
    ? ["Dispositivo", "Número de serie", "Sello de tiempo del dispositivo", "Tipo de registro", `Historial de glucosa ${unit}`, `Escaneo de glucosa ${unit}`, "Insulina de acción rápida (unidades)", "Carbohidratos (gramos)", "Notas"]
    : ["Device", "Serial Number", "Device Timestamp", "Record Type", `Historic Glucose ${unit}`, `Scan Glucose ${unit}`, "Rapid-Acting Insulin (units)", "Carbohydrates (grams)", "Notes"];
  const lines = [[opts.spanish ? "Datos de glucosa" : "Glucose Data", "Generated on", "x", "Generated by", "SYNTH"].join(d), head.join(d)];
  const start = opts.start ?? new Date(Date.UTC(2026, 0, 5, 0, 0));
  const n = opts.days * 96;
  for (let i = 0; i < n; i++) {
    const t = new Date(start.getTime() + i * 15 * 60000);
    const dd = pad(t.getUTCDate()), mm = pad(t.getUTCMonth() + 1), yy = t.getUTCFullYear();
    const stamp = opts.dmy ? `${dd}-${mm}-${yy} ${pad(t.getUTCHours())}:${pad(t.getUTCMinutes())}` : `${mm}-${dd}-${yy} ${pad(t.getUTCHours())}:${pad(t.getUTCMinutes())}`;
    const v = opts.value ? opts.value(i) : 120;
    const val = typeof v === "number" && unit === "mmol/L" ? `"${String(v).replace(".", ",")}"` : String(v);
    lines.push(["FreeStyle Libre 2 Plus", "SYNTH-0001", stamp, "0", val, "", "", "", ""].join(d));
  }
  return lines.join("\n");
}

const ok = (r: ReturnType<typeof parseCgmCsv>) => {
  if ("error" in r) throw new Error(r.error);
  return r as ParseResult;
};

describe("parser LibreView", () => {
  it("reconoce el formato inglés, unidades y deduce MM-DD por los datos", () => {
    const r = ok(parseCgmCsv(libreCsv({ days: 1 }), { timezone: TZ }));
    expect(r.format).toBe("libreview_csv");
    expect(r.unit).toBe("mg/dL");
    expect(r.readings).toHaveLength(96);
    expect(r.dateOrder).toBe("MDY");
    expect(r.readings[0].kind).toBe("historic");
  });
  it("reconoce cabeceras en español, punto y coma, mmol/L con coma decimal y DD-MM", () => {
    const csv = libreCsv({ days: 1, unit: "mmol/L", value: () => 5.5, spanish: true, dmy: true, delimiter: ";", start: new Date(Date.UTC(2026, 0, 13)) });
    const r = ok(parseCgmCsv(csv, { timezone: TZ }));
    expect(r.unit).toBe("mmol/L");
    expect(r.dateOrder).toBe("DMY");
    expect(r.readings[0].value).toBe(5.5);
    expect(r.readings[0].mgdl).toBeCloseTo(mmolToMgdl(5.5), 6);
  });
  it("convierte la hora local a UTC (invierno UTC+1)", () => {
    const r = ok(parseCgmCsv(libreCsv({ days: 1 }), { timezone: TZ }));
    expect(new Date(r.readings[0].ms).toISOString()).toBe("2026-01-04T23:00:00.000Z");
    expect(r.readings[0].localTime).toBe("2026-01-05T00:00");
  });
  it("descarta filas corruptas, detecta duplicados en el archivo y trata LO/HI", () => {
    let csv = libreCsv({ days: 1, value: (i) => (i === 3 ? "abc" : i === 4 ? "LO" : i === 5 ? "HI" : i === 6 ? 900 : 110) });
    const lines = csv.split("\n");
    lines.push(lines[10]); // duplicado exacto
    lines.push("garbage,row,without,date,,,");
    csv = lines.join("\n");
    const r = ok(parseCgmCsv(csv, { timezone: TZ }));
    expect(r.duplicatesInFile).toBe(1);
    expect(r.rejected.length).toBeGreaterThanOrEqual(3);
    expect(r.readings.find((x) => x.censored === "low")?.mgdl).toBe(40);
    expect(r.readings.find((x) => x.censored === "high")?.mgdl).toBe(500);
    expect(r.warnings.join(" ")).toMatch(/LO\/HI/);
  });
  it("pide mapeo manual si las columnas no se reconocen", () => {
    const r = parseCgmCsv("a,b,c\n1,2,3\n", { timezone: TZ });
    expect("error" in r).toBe(true);
  });
  it("con mapeo manual procesa un CSV genérico ISO", () => {
    const csv = "fecha,valor\n2026-02-01 08:00,100\n2026-02-01 08:15,105\n";
    const r = ok(parseCgmCsv(csv, { timezone: TZ, map: { time: 0, historic: 1 }, unit: "mg/dL" }));
    expect(r.format).toBe("generic_csv");
    expect(r.readings).toHaveLength(2);
    expect(r.dateOrder).toBe("YMD");
  });
  it("avisa cuando el orden de fecha es ambiguo y se deduce del idioma", () => {
    const csv = libreCsv({ days: 0.2, start: new Date(Date.UTC(2026, 1, 3)) });
    const r = ok(parseCgmCsv(csv, { timezone: TZ }));
    expect(r.dateOrderGuessed).toBe(true);
    expect(r.warnings[0]).toMatch(/orden de la fecha/);
  });
});

describe("métricas CGM", () => {
  const H = 3600000;
  const series = (days: number, f: (i: number) => number, interval = 15) =>
    Array.from({ length: (days * 1440) / interval }, (_, i) => ({ ms: i * interval * 60000, mgdl: f(i) }));

  it("TIR/TBR/TAR con dataset de referencia", () => {
    // 100 lecturas: 2 <54, 3 54–69, 70 en rango, 20 181–250, 5 >250
    const vals = [...Array(2).fill(50), ...Array(3).fill(60), ...Array(70).fill(120), ...Array(20).fill(200), ...Array(5).fill(300)];
    const rs = vals.map((v, i) => ({ ms: i * 15 * 60000, mgdl: v }));
    const m = computeMetrics(rs, 0, 100 * 15 * 60000);
    expect(m.pct.vlow).toBeCloseTo(2);
    expect(m.pct.low).toBeCloseTo(3);
    expect(m.pct.in).toBeCloseTo(70);
    expect(m.pct.high).toBeCloseTo(20);
    expect(m.pct.vhigh).toBeCloseTo(5);
    expect(m.pctBelow70).toBeCloseTo(5);
    expect(m.pctAbove180).toBeCloseTo(25);
    expect(m.coveragePct).toBeCloseTo(100);
  });
  it("media, DE y CV correctos", () => {
    const rs = [100, 200, 100, 200].map((v, i) => ({ ms: i * 900000, mgdl: v }));
    const m = computeMetrics(rs, 0, 4 * 900000);
    expect(m.mean).toBe(150);
    expect(m.sd).toBeCloseTo(57.735, 2);
    expect(m.cv).toBeCloseTo(38.49, 1);
  });
  it("límites: 180 en rango, 181 alto, 70 en rango, 69 bajo, 54 bajo nivel 1", () => {
    const c = (v: number) => classify({ ms: 0, mgdl: v }, CONSENSUS_RANGES);
    expect([c(180), c(181), c(70), c(69), c(54), c(53), c(250), c(251)]).toEqual(["in", "high", "in", "low", "low", "vlow", "high", "vhigh"]);
  });
  it("en mmol/L clasifica en la unidad original (10,0 en rango, 3,9 en rango)", () => {
    const r = (v: number) => ({ ms: 0, mgdl: mmolToMgdl(v), originalValue: v, originalUnit: "mmol/L" as const });
    expect(classify(r(10.0), CONSENSUS_RANGES)).toBe("in");
    expect(classify(r(10.1), CONSENSUS_RANGES)).toBe("high");
    expect(classify(r(3.9), CONSENSUS_RANGES)).toBe("in");
    expect(classify(r(3.8), CONSENSUS_RANGES)).toBe("low");
  });
  it("GMI solo con ≥14 días y ≥70 % de cobertura", () => {
    const full = series(14, () => 154);
    const m = computeMetrics(full, 0, 14 * 24 * H);
    expect(m.gmi).toBeCloseTo(7.0, 1); // 3.31 + 0.02392*154 = 6.99
    const short = computeMetrics(series(7, () => 154), 0, 7 * 24 * H);
    expect(short.gmi).toBeNull();
    const sparse = computeMetrics(full.filter((_, i) => i % 2 === 0), 0, 14 * 24 * H);
    expect(sparse.coveragePct).toBeCloseTo(50, 0);
    expect(sparse.gmi).toBeNull();
    expect(sparse.sufficient).toBe(false);
  });
  it("detecta huecos de datos", () => {
    const rs = series(1, () => 120).filter((r) => r.ms < 6 * H || r.ms >= 9 * H);
    const m = computeMetrics(rs, 0, 24 * H);
    expect(m.gaps).toHaveLength(1);
    expect(m.gaps[0].minutes).toBeGreaterThanOrEqual(180);
  });
});

describe("episodios", () => {
  it("requiere ≥15 min y cierra tras ≥15 min fuera", () => {
    const vals = [100, 65, 60, 62, 80, 85, 100, 66, 100, 100];
    const rs = vals.map((v, i) => ({ ms: i * 15 * 60000, mgdl: v }));
    const ep = detectEpisodes(rs, DEFAULT_EPISODE_RULES[0]);
    expect(ep).toHaveLength(2); // 65-60-62 (45 min) y 66 (15 min)
    expect(ep[0].extreme).toBe(60);
    expect(ep[0].minutes).toBe(45);
  });
  it("hiperglucemia prolongada solo si ≥120 min", () => {
    const rs = Array.from({ length: 12 }, (_, i) => ({ ms: i * 15 * 60000, mgdl: i < 7 ? 270 : 150 }));
    expect(detectEpisodes(rs, DEFAULT_EPISODE_RULES[2])).toHaveLength(0); // 105 min
    const rs2 = Array.from({ length: 12 }, (_, i) => ({ ms: i * 15 * 60000, mgdl: i < 9 ? 270 : 150 }));
    expect(detectEpisodes(rs2, DEFAULT_EPISODE_RULES[2])).toHaveLength(1);
  });
});

describe("AGP y contexto", () => {
  it("AGP: percentiles por franja con mínimo de datos", () => {
    const rs = Array.from({ length: 14 * 96 }, (_, i) => ({ mgdl: 100 + (i % 96 === 32 ? 50 : 0) + (Math.floor(i / 96) % 5) * 5, minuteOfDay: (i % 96) * 15 }));
    const agp = computeAgp(rs);
    expect(agp).toHaveLength(96);
    expect(agp[0].p50).not.toBeNull();
    expect(agp[0].p5!).toBeLessThanOrEqual(agp[0].p50!);
    expect(agp[0].p95!).toBeGreaterThanOrEqual(agp[0].p75!);
    expect(computeAgp(rs.slice(0, 96))[0].p50).toBeNull();
  });
  it("ejercicio ↔ glucosa: descriptivo y con mínimo de sesiones", () => {
    const rs = Array.from({ length: 96 * 10 }, (_, i) => ({ ms: i * 900000, mgdl: 150 }));
    const acts = [0, 1, 2].map((d) => ({ id: `a${d}`, label: "Carrera", group: "Carrera suave", start: d * 864e5 + 10 * 36e5, end: d * 864e5 + 11 * 36e5 }));
    // bajada durante cada sesión
    for (const a of acts) for (const r of rs) if (r.ms > a.start && r.ms <= a.end) r.mgdl = 100;
    const rows = activityGlucose(rs, acts);
    expect(rows.every((r) => r.coverageOk)).toBe(true);
    const obs = observations(summarizeGroups(rows));
    expect(obs[0]).toMatch(/bajó una mediana de 50 mg\/dL/);
    expect(obs.join(" ")).not.toMatch(/insulina|unidades|reduce/i);
  });
  it("PDF AGP: extrae métricas agregadas de texto", () => {
    const s = parseAgpText("Time in Ranges Very High >250 mg/dL 4% High 181-250 mg/dL 22% Target Range 70-180 mg/dL 70% Low 54-69 mg/dL 3% Very Low <54 mg/dL 1% Average Glucose 154 mg/dL Glucose Management Indicator (GMI) 7.0% Glucose Variability 33.2% % Time CGM is Active 96%");
    expect(s).toMatchObject({ pctVeryHigh: 4, pctHigh: 22, pctInRange: 70, pctLow: 3, pctVeryLow: 1, meanMgdl: 154, gmi: 7, cv: 33.2, activePct: 96 });
  });
});
